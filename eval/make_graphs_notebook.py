#!/usr/bin/env python3
"""Build a CPU-only Kaggle notebook that builds our own code graphs (triage/build_graph.py) for
competition tasks, from their repository snapshots, in the competition's graph format.

The outputs replace the competition's precomputed graphs in the evaluation, to test whether the
pipeline depends on them (`--graphs results/graphs_ast` in triage_localize.py, triage_reports.py and
triage_pipeline.py). Needs no GPU quota.

Usage:
    python eval/make_graphs_notebook.py --owner <kaggle_user> [--subsets dev holdout]
    kaggle kernels push -p notebooks/gemma4-ast-graphs
    kaggle kernels output <kaggle_user>/gemma4-ast-graphs -p results/graphs_ast
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "eval"))
from make_repro_check_notebook import DOCKER_IMAGE, code_cell, md_cell  # noqa: E402

BUILD_CELL = r'''
import json, shutil, subprocess, sys, tempfile, time
from pathlib import Path

DATA_DIR = next(Path(c) for c in ('/kaggle/input/competitions/gemma-4-developer-agent',
                                  '/kaggle/input/gemma-4-developer-agent') if Path(c).exists())
OUT = Path('/kaggle/working')
pkg = Path(tempfile.mkdtemp()) / 'triage'
pkg.mkdir()
for name, text in PACKAGE.items():
    (pkg / name).write_text(text)
sys.path.insert(0, str(pkg.parent))
from triage.build_graph import build_graph

tasks = {t['instance_id']: t for t in map(json.loads, (DATA_DIR / 'tasks.jsonl').read_text().splitlines())}
done, t0 = {}, time.time()
for tid in TASK_IDS:
    t = tasks[tid]
    name = f"{t['repo'].split('/')[-1]}_{t['base_commit']}"
    if name in done:
        continue
    work = Path(tempfile.mkdtemp(prefix='graph_'))
    try:
        subprocess.run(['tar', '-xzf', str(DATA_DIR / 'snapshots' / f'{tid}.tgz'), '-C', str(work)], check=True)
        s = time.time()
        g = build_graph(work, name)
        (OUT / f'{name}.json').write_text(json.dumps(g))
        done[name] = {'task': tid, 'nodes': len(g['nodes']), 'edges': len(g['edges']), 'seconds': round(time.time() - s, 2)}
    finally:
        shutil.rmtree(work, ignore_errors=True)
    print(f"[{len(done)}] {name}: {done[name]}", flush=True)
(OUT / 'graphs_summary.json').write_text(json.dumps(done, indent=1))
print(f'{len(done)} graphs in {(time.time() - t0) / 60:.1f} min')
'''


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--owner", required=True)
    ap.add_argument("--subsets", nargs="+", default=["dev", "holdout"])
    ap.add_argument("--labels", type=Path, default=ROOT / "results" / "triage" / "labels.jsonl")
    ap.add_argument("--slug", default="gemma4-ast-graphs")
    args = ap.parse_args()
    task_ids = [l["task_id"] for l in map(json.loads, args.labels.read_text().splitlines())
                if l and l["subset"] in args.subsets]
    package = {p.name: p.read_text() for p in (ROOT / "triage").glob("*.py")}
    params = f"TASK_IDS = {json.dumps(task_ids)}\nPACKAGE = {json.dumps(package)}\n"
    nb = {"cells": [md_cell(f"# Our own code graphs for {len(task_ids)} tasks\n\nGenerated by "
                            "`eval/make_graphs_notebook.py`: builds `triage/build_graph.py` graphs from each "
                            "task's snapshot. CPU only."), code_cell(params), code_cell(BUILD_CELL)],
          "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                       "language_info": {"name": "python"}},
          "nbformat": 4, "nbformat_minor": 5}
    out = ROOT / "notebooks" / args.slug
    out.mkdir(parents=True, exist_ok=True)
    (out / f"{args.slug}.ipynb").write_text(json.dumps(nb, indent=1) + "\n", encoding="utf-8")
    meta = {"id": f"{args.owner}/{args.slug}", "title": args.slug, "code_file": f"{args.slug}.ipynb",
            "language": "python", "kernel_type": "notebook", "is_private": True, "enable_gpu": False,
            "enable_tpu": False, "enable_internet": False, "dataset_sources": [],
            "competition_sources": ["gemma-4-developer-agent"], "kernel_sources": [], "model_sources": [],
            "docker_image": DOCKER_IMAGE, "docker_image_pinning_type": "original"}
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {out}/ for {len(task_ids)} tasks ({', '.join(args.subsets)})")


if __name__ == "__main__":
    main()
